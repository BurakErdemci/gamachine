"""Read Claude Code session files (<claude config dir>/projects/<folder>/<id>.jsonl).

Pure helpers, no FastAPI: find a session by id, extract the text a person
would have seen in the terminal, and build the command that resumes it there.
"""
import json
import os
import re
import unicodedata
from pathlib import Path
from typing import Any, Dict, Optional

SESSION_ID_RE = re.compile(
    r"[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}\Z")

MESSAGE_CAP_CHARS = 100_000
TITLE_MAX = 80

# Wrapper text Claude Code stores as user lines that no person typed.
_SKIP_USER_PREFIXES = ("<command-name>", "<local-command-", "<system-reminder>",
                       "[Request interrupted", "Base directory for this skill",
                       "<bash-input>", "<bash-stdout>", "<bash-stderr>", "<command-message>",
                       "<command-args>", "<user-prompt-submit-hook>",
                       # Claude Code's own local-command caveat, not any prompt that starts with "Caveat:".
                       "Caveat: The messages below were generated by the user while running local commands")


def projects_dir() -> Path:
    base = os.environ.get("CLAUDE_CONFIG_DIR") or os.path.join(os.path.expanduser("~"), ".claude")
    return Path(base) / "projects"


def valid_session_id(session_id: Any) -> bool:
    return isinstance(session_id, str) and SESSION_ID_RE.fullmatch(session_id) is not None


def cwd_usable(cwd: Any) -> bool:
    """An absolute local folder string: no relative path, no UNC share (isdir on it can touch the network)."""
    return (isinstance(cwd, str) and os.path.isabs(cwd) and not cwd.startswith(("\\\\", "//", "\\/", "/\\"))
            and not any(ord(ch) < 32 or ord(ch) == 127 for ch in cwd))


def find_session(session_id: str) -> Optional[Path]:
    """The session file for a UUID, or None. Only the validated id is joined into a path."""
    if not valid_session_id(session_id):
        return None
    try:
        folders = [d for d in projects_dir().iterdir() if d.is_dir()]
    except OSError:
        return None
    found = []
    try:
        root = projects_dir().resolve()
    except OSError:
        return None
    for folder in folders:
        candidate = folder / f"{session_id}.jsonl"
        try:
            # A link inside the store must not lead to a file outside it.
            if candidate.is_file() and candidate.resolve().is_relative_to(root):
                found.append((candidate.stat().st_mtime, candidate))
        except OSError:
            continue
    if not found:
        return None
    return max(found, key=lambda item: item[0])[1]


def _human_text(message: Any) -> Optional[str]:
    """A person's prompt from a user line, or None for tool results and wrappers."""
    content = message.get("content") if isinstance(message, dict) else None
    if isinstance(content, str):
        text = content
    elif isinstance(content, list):
        blocks = [b for b in content if isinstance(b, dict)]
        if any(b.get("type") == "tool_result" for b in blocks):
            return None
        text = "".join(str(b.get("text") or "") for b in blocks if b.get("type") == "text")
        if not text.strip() and any(b.get("type") == "image" for b in blocks):
            text = "[resim]"
    else:
        return None
    text = text.strip()
    if not text or text.startswith(_SKIP_USER_PREFIXES):
        return None
    return text


def _assistant_text(message: Any) -> Optional[str]:
    content = message.get("content") if isinstance(message, dict) else None
    if isinstance(content, str):
        text = content
    elif isinstance(content, list):
        text = "".join(str(b.get("text") or "") for b in content
                       if isinstance(b, dict) and b.get("type") == "text")
    else:
        return None
    return text.strip() or None


def read_session(path: Path, limit: int = 300) -> Dict[str, Any]:
    """Visible messages of a session file (the last `limit`), plus its first cwd and last model."""
    path = Path(path)
    cwd = None
    model = None
    title = None
    total = 0
    kept: list = []
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        for raw in fh:
            try:
                line = json.loads(raw)
            except ValueError:
                continue
            if not isinstance(line, dict):
                continue
            kind = line.get("type")
            if kind == "system" and line.get("subtype") == "compact_boundary":
                # What the terminal still has after a /compact: the messages it kept
                # (compactMetadata.preservedMessages) and everything after the boundary.
                # Measured on a Claude Code 2.1.3xx file: the kept ones sit just before it.
                meta = line.get("compactMetadata") if isinstance(line.get("compactMetadata"), dict) else {}
                pm = meta.get("preservedMessages") if isinstance(meta.get("preservedMessages"), dict) else {}
                preserved = set(pm.get("allUuids") or pm.get("uuids") or [])
                kept = [m for m in kept if m.get("uuid") in preserved]
                total = len(kept)
                continue
            if kind not in ("user", "assistant"):
                continue
            # The first line's cwd wins: a later Bash `cd` changes it inside one file.
            if cwd is None and isinstance(line.get("cwd"), str) and line["cwd"]:
                cwd = line["cwd"]
            if line.get("isSidechain") or line.get("isMeta") or line.get("isCompactSummary"):
                continue
            message = line.get("message")
            if kind == "user":
                if "toolUseResult" in line:
                    continue
                text = _human_text(message)
            else:
                text = _assistant_text(message)
                msg_model = message.get("model") if isinstance(message, dict) else None
                if text and isinstance(msg_model, str) and msg_model:
                    model = msg_model
            if not text:
                continue
            if kind == "user" and title is None:
                title = text.splitlines()[0].strip()[:TITLE_MAX]
            total += 1
            kept.append({"role": kind, "content": text[:MESSAGE_CAP_CHARS],
                         "timestamp": line.get("timestamp"), "uuid": line.get("uuid")})
            if limit > 0 and len(kept) > limit:
                kept.pop(0)
    return {"session_id": path.stem, "cwd": cwd, "model": model, "title": title or "",
            "messages": kept, "total": total, "modified_at": path.stat().st_mtime}


# Allowlist, not a denylist: PowerShell also reads Unicode quotes (U+2018-U+201E)
# and dashes as syntax, so anything outside letters, digits (str.isalnum, Turkish
# letters included), combining marks on a letter (Finder stores names decomposed)
# and these few characters gets no cd part. A backslash is a path separator only
# on Windows: elsewhere bash reads it as an escape inside "...".
_CD_SAFE = frozenset(" \\/:._-()")


def _cd_safe(cwd: str) -> bool:
    if os.name != "nt" and "\\" in cwd:
        return False
    on_letter = False
    for ch in cwd:
        if on_letter and unicodedata.category(ch).startswith("M"):
            continue
        if not (ch.isalnum() or ch in _CD_SAFE):
            return False
        on_letter = ch.isalpha()
    return True


def command_for(cwd: Optional[str], session_id: str) -> str:
    """`cd "<cwd>"; claude --resume <id>`, valid in PowerShell, bash and zsh.

    A cwd with any character outside the allowlist (_cd_safe) cannot be quoted
    the same way in all three shells, so the cd part is dropped rather than risk
    a command that does something else; the caller shows the plain resume command.
    """
    resume = f"claude --resume {session_id}"
    if not cwd or cwd[-1] in "\\/" or not _cd_safe(cwd):
        return resume
    return f'cd "{cwd}"; {resume}'
