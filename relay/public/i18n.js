let lang = 'en';
try {
  const saved = globalThis.localStorage?.getItem('gm-ui-lang');
  if (saved === 'en' || saved === 'tr') lang = saved;
} catch {}

export function getLang() { return lang; }

export function setLang(value) {
  if (value !== 'en' && value !== 'tr') return;
  lang = value;
  try { globalThis.localStorage?.setItem('gm-ui-lang', lang); } catch {}
}

export function t(key, vars = {}) {
  const value = Object.prototype.hasOwnProperty.call(STRINGS[lang], key) ? STRINGS[lang][key] : key;
  return value.replace(/\{(\w+)\}/g, (token, name) => Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : token);
}

export function applyStatic(root = document) {
  const doc = root.ownerDocument || root;
  doc.documentElement.lang = lang;
  const nodes = [...root.querySelectorAll('[data-i18n], [data-i18n-attr]')];
  if (root.matches?.('[data-i18n], [data-i18n-attr]')) nodes.unshift(root);
  for (const node of nodes) {
    if (node.dataset.i18n) node.textContent = t(node.dataset.i18n);
    for (const entry of (node.dataset.i18nAttr || '').split(';')) {
      const at = entry.indexOf(':');
      if (at > 0) node.setAttribute(entry.slice(0, at), t(entry.slice(at + 1)));
    }
  }
}
